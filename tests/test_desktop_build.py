"""The Desktop half's build box (PLAN M5): desktop/plugin.js is the build of desktop/src, the runtime
loader accepts it, module evaluation stays under 100 ms and register() makes its contributions,
Hermes' admission lint is clean and the install scan says `safe`, and the bundle keeps the plugin's
own rules: only the three specifiers Desktop provides, no eval or string-built code or script tags, no
hard-coded colours, and no route outside the pinned contract.

Colour exception, on purpose: the physical card keeps its fixed paper colours (stock, ink, the paper's
own lines and shadow) in light and dark, like a printed card on any table: white with black text on
the human face, black with white text on the agent face (A16, PLAN-v0.1.3). They live only between the `/* card-stock:start */` and `/* card-stock:end */` markers in
desktop/src/style.js; every other colour is a Desktop theme variable.

The build tests need node and `npm ci` in desktop/build; without them they are skipped. The Hermes
checks also need Hermes' own Python at /opt/hermes/.venv.
"""
