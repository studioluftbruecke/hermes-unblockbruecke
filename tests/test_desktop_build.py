def _last_json(text: str) -> dict:
    return json.loads(text.strip().splitlines()[-1])


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _bundle() -> str:
    return BUNDLE.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def fresh_build(tmp_path_factory):
    out = tmp_path_factory.mktemp("ubk-build")
    run = subprocess.run([NODE, str(BUILD / "build.mjs"), "--out", str(out)], capture_output=True, text=True, timeout=600)
    report = _last_json(run.stdout)
    report["_out"] = out
    return report


def test_bundle_is_committed_with_its_version_banner():
    src = _bundle()
    version = re.search(r'^version:\s*"?([^"\s]+)"?', (ROOT / "plugin.yaml").read_text(encoding="utf-8"), re.M).group(1)
    assert src.splitlines()[0].startswith(f"// Unblockbruecke (unblockbruecke) {version}, Desktop half. Generated by desktop/build/build.mjs")
    assert version == "0.2.0"
    assert len(src.encode()) < 1024 * 1024
    assert src.isascii(), "esbuild writes ASCII; a raw non-ASCII character would reach the install scan"


