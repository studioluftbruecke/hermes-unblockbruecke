"""The Desktop half's build box (PLAN M5): desktop/plugin.js is the build of desktop/src, the runtime
loader accepts it, module evaluation stays under 100 ms and register() makes its contributions,
Hermes' admission lint is clean and the install scan says `safe`, and the bundle keeps the plugin's
own rules: only the three specifiers Desktop provides, no eval or string-built code or script tags, no
hard-coded colours, and no route outside the pinned contract.

Colour exception, on purpose: the physical card (mockups/concept.html, approved) keeps its fixed paper
colours (stock, ink, the paper's own lines and shadow) in light and dark, like a printed card on any
table. They live only between the `/* card-stock:start */` and `/* card-stock:end */` markers in
desktop/src/style.js; every other colour is a Desktop theme variable.

The build tests need node and `npm ci` in desktop/build; without them they are skipped. The Hermes
checks also need Hermes' own Python at /opt/hermes/.venv.
"""
import hashlib
import json
import re
import shutil
import subprocess
from pathlib import Path

import pytest

from ub_fakes import ROOT

DESKTOP = ROOT / "desktop"
BUILD = DESKTOP / "build"
BUNDLE = DESKTOP / "plugin.js"
SRC = DESKTOP / "src"
NODE = shutil.which("node")
HERMES_PY = Path("/opt/hermes/.venv/bin/python")
CONTRACT = ROOT.parents[1] / "experiments" / "unblockbruecke" / "v0.1-contract.md"
needs_node = pytest.mark.skipif(not NODE or not (BUILD / "node_modules" / "esbuild").is_dir(),
                                reason="node and desktop/build/node_modules (npm ci) are needed for the Desktop build box")

# The contract's route table (v0.1-contract.md §5), pinned here so the test also runs in the exported
# plugin tree, where experiments/ is absent; when the contract file is present the two must agree.
CONTRACT_ROUTES = {
    ("GET", "/health"), ("GET", "/decks"), ("GET", "/decks/{slug}"), ("POST", "/draw"), ("GET", "/today"),
    ("GET", "/journal"), ("POST", "/journal/rate"), ("POST", "/journal/reset"), ("POST", "/decks/{slug}/preview"),
    ("PUT", "/decks/{slug}"), ("GET", "/decks/{slug}/versions"), ("POST", "/decks/{slug}/restore"),
    ("POST", "/decks/{slug}/delete"), ("POST", "/decks/import"), ("GET", "/decks/{slug}/export"), ("GET", "/settings"),
    ("PUT", "/settings/decks"),
}
ALLOWED_SPECIFIERS = {"@hermes/plugin-sdk", "react", "react/jsx-runtime"}


def _last_json(text: str) -> dict:
    return json.loads(text.strip().splitlines()[-1])


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _bundle() -> str:
    return BUNDLE.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def fresh_build(tmp_path_factory):
    out = tmp_path_factory.mktemp("ubk-build")
    run = subprocess.run([NODE, str(BUILD / "build.mjs"), "--out", str(out)], capture_output=True, text=True, timeout=600)
    report = _last_json(run.stdout)
    report["_out"] = out
    return report


def test_bundle_is_committed_with_its_version_banner():
    src = _bundle()
    version = re.search(r'^version:\s*"?([^"\s]+)"?', (ROOT / "plugin.yaml").read_text(encoding="utf-8"), re.M).group(1)
    assert src.splitlines()[0].startswith(f"// UnblockBruecke Cards (unblockbruecke) {version}, Desktop half. Generated by desktop/build/build.mjs")
    assert version == "0.1.0"
    assert len(src.encode()) < 1024 * 1024
    assert src.isascii(), "esbuild writes ASCII; a raw non-ASCII character would reach the install scan"


@needs_node
def test_committed_bundle_equals_a_fresh_build(fresh_build):
    assert fresh_build["plugin_js"]["sha256"] == _sha(BUNDLE), \
        "desktop/plugin.js is stale: run node desktop/build/build.mjs and commit it"
    assert fresh_build["plugin_js"]["underCap"]


@needs_node
def test_loader_accepts_it_and_evaluation_is_in_budget(fresh_build):
    scan = fresh_build["loaderScan"]
    assert scan.get("skipped") or (scan["ok"] and scan["unsupported"] == [] and scan["controlRefused"])
    ev = fresh_build["evaluation"]
    print("evaluation CPU ms", ev["cpuMsRuns"], "min", ev["cpuMsMin"], "median", ev["cpuMsMedian"], "load", ev["loadAverage"])
    assert ev["withinBudget"], f"module evaluation {ev['cpuMsMin']} ms CPU (min of 5) is over {ev['budgetMs']} ms"
    assert ev["registered"]
    ids = {c.split(":", 1)[1] for c in ev["contributions"]}
    assert {"page", "chip", "directive-card", "draw-key", "cards", "palette-draw", "palette-decks"} <= ids


