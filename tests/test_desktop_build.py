def test_imports_only_the_three_specifiers_desktop_provides():
    src = _bundle()
    static = set(re.findall(r'\}\s*from\s*["\']([^"\']+)["\']', src)) | set(re.findall(r'(?<![\w"\'./-])import\s*\w*\s*(?:from\s*)?["\']([^"\']+)["\']', src))
    assert static and static <= ALLOWED_SPECIFIERS, static - ALLOWED_SPECIFIERS
    # The runtime loader's own scan (build.mjs, loaderScan) is the authority; this is the quick twin.
    assert not re.search(r"\bimport\s*\(", src), "no dynamic import"
    assert not re.search(r"\brequire\s*\(", src), "no CommonJS require left in the bundle"


def test_no_eval_no_string_code_no_script_tags():
    src = _bundle()
    assert not re.search(r"\beval\s*\(", src)
    assert not re.search(r"\bnew\s+Function\b|\bFunction\s*\(", src)
    assert "<script" not in src.lower()
    assert not re.search(r"\b(innerHTML|outerHTML|insertAdjacentHTML|dangerouslySetInnerHTML)\b", src)
    assert not re.search(r"setTimeout\s*\(\s*[\"'`]", src)


COLOUR = re.compile(r"#[0-9a-fA-F]{3,8}\b(?![-\w])|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch)\s*\(|(?<![-\w])(?:black|white)(?![-\w])")


def _strip_stock(text: str) -> str:
    start, end = "/* card-stock:start */", "/* card-stock:end */"
    assert text.count(start) == 1 and text.count(end) == 1, "the card-stock block must appear exactly once"
    i, j = text.index(start), text.index(end)
    return text[:i] + text[j + len(end):]


def test_no_hard_coded_colours_outside_the_card_stock():
    rest = _strip_stock(_bundle())
    found = [m.group(0) for m in COLOUR.finditer(rest)]
    assert found == [], found
    for f in SRC.glob("*.js"):
        text = f.read_text(encoding="utf-8")
        if "card-stock:start" in text:
            text = _strip_stock(text)
        assert [m.group(0) for m in COLOUR.finditer(text)] == [], f.name
    stock = _bundle().split("/* card-stock:start */")[1].split("/* card-stock:end */")[0]
    assert "--ubk-stock:" in stock and "#f3f2ee" in stock, "the card keeps the approved paper colour"


def _api_routes() -> set:
    api = (SRC / "api.js").read_text(encoding="utf-8")
    found = set()
    for m in re.finditer(r"(?:rest|post|put)\(\s*(['`])(/[^'`]*)\1(?:\s*,\s*\{\s*method:\s*'(\w+)')?", api):
        helper = api[m.start():m.start() + 4]
        method = m.group(3) or {"post": "POST", "put(": "PUT"}.get(helper, "GET")
        path = re.sub(r"\$\{enc\(slug\)\}", "{slug}", m.group(2)).split("?")[0]
        found.add((method, path))
    return found


def test_every_route_the_bundle_calls_is_in_the_contract():
    routes = _api_routes()
    assert routes == CONTRACT_ROUTES, {"not in contract": routes - CONTRACT_ROUTES, "unused": CONTRACT_ROUTES - routes}
    for f in SRC.glob("*.js"):
        if f.name not in ("api.js", "core.js"):
            assert not re.search(r"\brest\(", f.read_text(encoding="utf-8")), f"{f.name} calls rest() outside api.js"
    if CONTRACT.exists():
        table = set()
        for line in CONTRACT.read_text(encoding="utf-8").splitlines():
            m = re.match(r"\|\s*(GET|POST|PUT)\s*\|\s*`([^`]+)`", line)
            if m:
                table.add((m.group(1), m.group(2)))
        assert table == CONTRACT_ROUTES, "the pinned list above drifted from v0.1-contract.md §5"
    src = _bundle()
    for _, path in routes:
        literal = path.split("{slug}")[0] if "{slug}" in path else path
        assert literal in src


